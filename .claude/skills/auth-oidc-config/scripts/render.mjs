// Pure renderers: inputs -> file contents. No I/O, no randomness, no timestamps (outputs are reproducible).
import { issuerOf, jwksOf } from './lib.mjs';

export function renderBackendYaml(i) {
  return `# Generated by auth-oidc-config. Spring Boot resource server (JWT). No secrets.
spring:
  security:
    oauth2:
      resourceserver:
        jwt:
          issuer-uri: \${AUTH_ISSUER:${issuerOf(i)}}   # trailing slash is part of the issuer
app:
  security:
    audience: \${AUTH_AUDIENCE:${i.api.identifier}}
    roles-claim: \${AUTH_ROLES_CLAIM:${i.roles.claim}}
    cors:
      allowed-origins: \${CORS_ALLOWED_ORIGINS:${i.backend.corsOrigins.join(',')}}
`;
}

export function renderEnvExample(i) {
  return `# Generated by auth-oidc-config. Non-secret values only.
AUTH_ISSUER=${issuerOf(i)}
AUTH_AUDIENCE=${i.api.identifier}
AUTH_ROLES_CLAIM=${i.roles.claim}
CORS_ALLOWED_ORIGINS=${i.backend.corsOrigins.join(',')}
`;
}

export function renderFrontendConfig(i) {
  return JSON.stringify({
    auth: {
      enabled: true,
      domain: i.tenantDomain,
      clientId: i.spa.clientId,
      audience: i.api.identifier,
      scope: 'openid profile email offline_access',
      redirectUri: i.spa.callbackUrls[0],
      rolesClaim: i.roles.claim,
    },
    apiBaseUrl: i.frontend.apiBaseUrl,
  }, null, 2) + '\n';
}

export function renderPostLoginAction(i) {
  const allowed = JSON.stringify(i.roles.allowed);
  return `// Generated by auth-oidc-config. Paste in Auth0: Actions > Library > Build Custom > Trigger "Login / Post Login".
// Deploy it, then attach it to the Login flow (Actions > Triggers > post-login), otherwise the claim is never issued.
exports.onExecutePostLogin = async (event, api) => {
  const namespace = '${i.roles.claim}';
  const allowed = ${allowed};
  const assigned = (event.authorization?.roles ?? []).filter((role) => allowed.includes(role));
  api.accessToken.setCustomClaim(namespace, assigned.length ? assigned : ['${i.roles.defaultRole}']);
};
`;
}

export function renderExpectedClaims(i) {
  return JSON.stringify({
    iss: issuerOf(i),
    aud: `contains ${i.api.identifier}`,
    azp: i.spa.clientId,
    sub: 'auth0|<user id>',
    [i.roles.claim]: i.roles.allowed.map((r) => `one of: ${r}`),
    alg: 'RS256',
    jwks: jwksOf(i),
  }, null, 2) + '\n';
}

export function renderPortalChecklist(i) {
  const list = (items) => items.map((x) => `\`${x}\``).join(', ');
  const users = (i.testUsers ?? []).map((u) => `${u.label ?? 'user'} -> \`${u.sub}\``).join('; ') || '(none yet)';
  return `# Auth0 portal checklist — ${i.tenantDomain}

Generated from your inputs. Tick each item and keep the evidence line (what you saw). Secrets never go in this file.

## 1. Application (Applications > Applications > ${i.spa.name ?? 'your app'})
- [ ] **Application Type = Single Page Application** (Settings > Application Properties). Client ID is \`${i.spa.clientId}\`.
- [ ] **Allowed Callback URLs:** ${list(i.spa.callbackUrls)}
- [ ] **Allowed Logout URLs:** ${list(i.spa.logoutUrls)}
- [ ] **Allowed Web Origins:** ${list(i.spa.webOrigins)}
- [ ] **Cross-Origin Authentication:** OFF. *Allowed Origins (CORS)* and *Fallback URL* stay empty (placeholder text like my-app.com is not a saved value).
- [ ] **Refresh Token Rotation:** ON (Settings > Refresh Token Rotation). Grant types: Authorization Code and Refresh Token (Advanced Settings > Grant Types).
- [ ] Click **Save Changes** at the bottom — Auth0 does not autosave.

## 2. API (Applications > APIs > Create API) — NOT the built-in "Auth0 Management API"
- [ ] **Name:** ${i.api.name ?? 'your API'}
- [ ] **Identifier:** \`${i.api.identifier}\` (cannot be changed later; it is the token audience)
- [ ] **Signing Algorithm:** RS256
- [ ] Settings: **Allow Offline Access** ON (refresh tokens).
- [ ] Application Access: *User access* = authorized for \`${i.spa.name ?? 'your app'}\` (or "All apps" for a single-app tenant); *Client access* = No apps.
- [ ] No permissions/scopes are needed: authorization uses the role claim.

## 3. Post-Login Action (Actions > Library > Build Custom)
- [ ] Trigger **Login / Post Login**, paste \`auth0-post-login-roles.js\`, **Deploy**.
- [ ] Actions > Triggers > post-login: drag the Action **into the flow** and **Apply**.

## 4. Users and sign-up (User Management > Users; Authentication > Database)
- [ ] Create the test users (Database connection \`Username-Password-Authentication\`). Roles you will use: ${list(i.roles.allowed)}.
- [ ] **Disable Sign Ups** on that connection.
- [ ] Record each user's \`user_id\` (= token \`sub\`): ${users}

## 5. Verify (deterministic)
- [ ] \`node scripts/check-inputs.mjs inputs.json\` -> VALID
- [ ] \`node scripts/verify-tenant.mjs inputs.json\` -> issuer and JWKS OK (public endpoints only)
- [ ] After a real login, paste only the **access token** into \`node scripts/decode-token.mjs inputs.json\` (stdin) -> all checks OK
`;
}

export const OUTPUT_FILES = (i) => ({
  'backend/application-auth.yaml': renderBackendYaml(i),
  'backend/auth.env.example': renderEnvExample(i),
  'frontend/config.json': renderFrontendConfig(i),
  'portal/auth0-post-login-roles.js': renderPostLoginAction(i),
  'portal/expected-token-claims.json': renderExpectedClaims(i),
  'portal/portal-checklist.md': renderPortalChecklist(i),
});
